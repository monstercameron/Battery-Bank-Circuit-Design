def net_voltages(D):
    """Worst-case net voltages (docs/design-rules.md 1.3). Exact entries first, then prefixes."""
    for net, v in {"GND": 0.0, "VBAT": 21.0, "V3V3": 3.6, "V3V3_ETH": 3.6, "V3V3_LORA": 3.6, "V5_PD": 5.5,
                   "V5_AUX": 5.5, "V5_GLOW": 5.5, "V5_ETH": 5.5, "V0V95_PHY": 1.0, "V5_FAN": 5.5, "V12_QI": 12.4, "V12_RTR": 12.4, "V0V95_SW": 1.0,
                   "VDCIN": 24.3, "VIN_AUX": 24.3, "VPOE": 22.0, "VDCOUT": 24.0, "VDCOUT_RAW": 24.0,
                   "PD_INT_N": 3.6, "CHG_INT_N": 3.6, "I2C_SDA": 3.6, "I2C_SCL": 3.6}.items():
        D.v(net, v)
    for prefix, v in [("I2C", 3.6), ("SW_P", 3.6), ("POE_", 57.0), ("PSE", 57.0), ("PRI_", 57.0),
                      ("VBUS_C", 28.0), ("VIN_C", 28.0), ("ESP_", 3.6), ("EXP_", 3.6), ("LORA_", 3.6),
                      ("ETH_", 3.6), ("AUD_", 5.5), ("LED_", 5.5), ("USBA_", 12.6), ("QI_", 12.6),
                      ("DCO_", 24.0), ("DCI_", 24.3), ("INS_", 24.3), ("CART_", 21.0), ("SEC_", 22.0),
                      ("RTR_", 12.6), ("NFC_", 3.6)]:
        D.vp(prefix, v)
    # anything ending in a per-port suffix defaults to the logic level unless set exactly
    for k in range(1, 5):
        D.vp(f"", 0)  # placeholder removed below
    D.net_v_prefix = [p for p in D.net_v_prefix if p[0]]


# Board-to-board interconnect -------------------------------------------------------------
# Header pin rating 3 A (2.54 mm stacking header) -> 1 A per pin under the 3:1 rule.
PIN_RATING_A = 3.0
NET_CURRENT_A = {  # worst-case continuous current per crossing power net (docs/power-budget.md)
    "V12_RTR": 0.92, "V12_QI": 0.6, "V5_AUX": 1.0, "V5_GLOW": 0.4, "V5_ETH": 0.2, "V3V3": 0.3, "V3V3_LORA": 0.2,
    "V3V3_ETH": 0.4, "VPOE": 2.6, "VBAT": 2.0,
}
HS_PREFIXES = ("ETH_S0", "ETH_S1", "ETH_PHY_HS", "RTR_RX", "RTR_TX")


def board_of(part):
    return str(part.fields.get("Board") or getattr(part.sheet, "board", "A"))


def interconnect(D):
    """Add mating board-to-board connectors (A side + B side) carrying every net that spans boards A and B."""
    import math
    cross = []
    for net, pins in sorted(D.netlist().items()):
        boards = {board_of(p) for p, _ in pins if not p.fields.get("B2B")}
        if {"A", "B"} <= boards:
            cross.append(net)
    hs = [n for n in cross if n.startswith(HS_PREFIXES)]
    ls = [n for n in cross if n not in hs and n != "GND"]
    sh = D.sheet("interconnect", "Board-to-board interconnect (generated): A <-> B", board="A")
    sh.note("Generated by build.py: every net spanning boards A and B. Power pins sized 3:1 (1 A per 3 A pin).")
    # low-speed + power header
    pins, conns = [], {}
    n_pow = 0
    for net in ls:
        k = max(1, math.ceil(3 * NET_CURRENT_A.get(net, 0.0) / PIN_RATING_A))
        n_pow += k if net in NET_CURRENT_A else 0
        for i in range(k):
            pn = f"{net}#{i+1}" if k > 1 else net
            pins.append(pn)
            conns[pn] = net
    n_gnd = max(4, n_pow + math.ceil(len(ls) / 4))
    for i in range(n_gnd):
        pins.append(f"GND#{i+1}")
        conns[f"GND#{i+1}"] = "GND"
    if len(pins) % 2:
        pins.append(f"GND#{n_gnd+1}")
        conns[pins[-1]] = "GND"
    n = len(pins)
    for side, fp in (("A", f"Connector_PinHeader_2.54mm:PinHeader_2x{n//2:02d}_P2.54mm_Vertical"),
                     ("B", f"Connector_PinSocket_2.54mm:PinSocket_2x{n//2:02d}_P2.54mm_Vertical")):
        D.CONN(sh, f"B2B_LS_{n}P_{side}", pins, conns, footprint=fp, prefix="J",
               fields={"Board": side, "B2B": True, "Rated_I": PIN_RATING_A, "Consigned": True,
                       "Note": f"2x{n//2} 2.54 mm stacking pair (A header / B socket), 18.4 mm stack. LCSC part TBD at layout."})
    # high-speed SerDes mezzanine: G-S-S-G per pair
    hpins, hconns = [], {}
    pairs = sorted({n[:-1] for n in hs})
    g = 0
    for pr in pairs:
        for pn in (f"GND#{g+1}", pr + "P", pr + "N"):
            if pn.startswith("GND"):
                g += 1
                hconns[pn] = "GND"
            else:
                hconns[pn] = pn
            hpins.append(pn)
    g += 1
    hpins.append(f"GND#{g}")
    hconns[f"GND#{g}"] = "GND"
    for side in ("A", "B"):
        D.CONN(sh, f"B2B_HS_{len(hpins)}P_{side}", hpins, hconns, footprint="", prefix="J",
               fields={"Board": side, "B2B": True, "Consigned": True,
                       "Note": "Differential-rated mezzanine (>= 5 Gbps, 18.4 mm stack), G-S-S-G pinout. Part TBD (H-3)."})
    D.cross_nets = cross
    return sh


def default_logic(D):
    """Nets without an explicit voltage are treated as 3.6 V logic for the derating check."""
    D.defaulted_nets = []
    for net in D.netlist():
        if net not in D.net_v and not any(net.startswith(p) for p, _ in D.net_v_prefix):
            D.net_v.setdefault(net, 3.6)
            D.defaulted_nets.append(net)


def bom(D, path):
    rows = {}
    for sh in D.sheets:
        for p in sh.parts:
            if p.fields.get("_nobom") or p.dnp:
                continue
            key = (p.value, p.footprint, p.fields.get("LCSC", ""))
            rows.setdefault(key, []).append(p.ref)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Comment", "Designator", "Footprint", "LCSC Part #", "Qty"])
        for (val, fp, lcsc), refs in sorted(rows.items(), key=lambda r: r[1][0]):
            w.writerow([val, ",".join(sorted(refs, key=lambda r: (r.rstrip("0123456789"), int("".join(c for c in r if c.isdigit()) or 0)))),
                        fp.split(":")[-1], lcsc, len(refs)])
    return len(rows), sum(len(v) for v in rows.values())


def build(only=None):
    D = Design()
    net_voltages(D)
    blocks = [("usbc_port", lambda: [usbc_port.build(D, k) for k in range(1, 5)]),
              ("power_input", lambda: power_input.build(D)), ("poe", lambda: poe.build(D)),
              ("battery", lambda: battery.build(D)), ("aux_power", lambda: aux_power.build(D)),
              ("ethernet", lambda: ethernet.build(D)), ("mcu", lambda: mcu.build(D)), ("lora", lambda: lora.build(D)),
              ("audio", lambda: audio.build(D)), ("lighting", lambda: lighting.build(D)),
              ("dc_output", lambda: dc_output.build(D)), ("usb_a", lambda: usb_a.build(D)), ("qi", lambda: qi.build(D))]
    for name, fn in blocks:
        if only and name not in only:
            continue
        fn()
    if not only:
        interconnect(D)
    default_logic(D)
    return D


def build_cartridge():
    from blocks import cartridge
    D = Design("battery-cartridge")
    net_voltages(D)
    cartridge.build(D)
    default_logic(D)
    return D


def main():
    global OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--project", default="main", choices=["main", "cartridge"])
    ap.add_argument("--stock", action="store_true", help="check JLCPCB stock for every LCSC part (network, cached)")
    ap.add_argument("--out", help="output folder (default hardware/kicad); use a scratch folder for parallel test builds")
    a = ap.parse_args()
    if a.project == "cartridge":
        OUT = os.path.join(ROOT, "kicad_cartridge")
        D = build_cartridge()
    else:
        D = build(a.only)
    if a.out:
        OUT = os.path.abspath(a.out)
    elif a.only:
        # X-36: a subset build never overwrites the released source set
        OUT = os.path.join(ROOT, "kicad_partial")
    # X-36: build into a staging folder; promote to OUT only if the checker AND KiCad ERC pass
    stage = OUT + ".staging"
    if os.path.isdir(stage):
        shutil.rmtree(stage)
    os.makedirs(stage)
    D.write(stage)
    write_project_files(stage, D.name)
    write_bb_library(D)
    n_lines, n_parts = bom(D, os.path.join(stage, "bom_jlcpcb.csv"))
    findings = check.run(D, stock=a.stock)
    erc = kicad_outputs(stage)
    if erc is None:
        if os.environ.get("BB_SKIP_ERC") != "1":
            findings.append(("ERROR", "ERC", "kicad-cli not found: KiCad ERC did not run (set BB_SKIP_ERC=1 to accept)"))
    else:
        e_err, e_warn = erc
        if e_err:
            findings.append(("ERROR", "ERC", f"KiCad ERC reports {e_err} errors (see erc.rpt)"))
        findings.append(("INFO", "ERC", f"KiCad ERC: {e_err} errors, {e_warn} warnings"))
    text, n_err = check.report(findings, os.path.join(stage, "design_check.txt"))
    print(text[-3000:])
    print(f"\nsheets={len(D.sheets)} parts={sum(len(s.parts) for s in D.sheets)} bom_lines={n_lines} bom_parts={n_parts}")
    if n_err:
        print(f"\nBUILD FAILED: {n_err} errors. Output left in {stage}; {OUT} not touched.")
        return 1
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):           # drop stale sheets (renamed/removed blocks), keep KiCad local state
        if f.endswith((".kicad_sch", ".kicad_pro", "-schematic.pdf", ".csv", ".rpt", "design_check.txt")):
            os.remove(os.path.join(OUT, f))
    for f in os.listdir(stage):
        shutil.move(os.path.join(stage, f), os.path.join(OUT, f))
    os.rmdir(stage)
    print(f"promoted -> {OUT}")
    return 0


KICAD_CLI = os.environ.get("KICAD_CLI", os.path.expandvars(r"%LOCALAPPDATA%\Programs\KiCad\10.0\bin\kicad-cli.exe"))


def kicad_outputs(out):
    """KiCad ERC report + a PDF of every sheet so the build can be watched as it progresses."""
    """Returns (errors, warnings) from KiCad's ERC, or None if kicad-cli is unavailable (X-35)."""
    import re
    import subprocess
    if not os.path.exists(KICAD_CLI):
        print("kicad-cli not found; skipping ERC/PDF")
        return None
    name = [f for f in os.listdir(out) if f.endswith(".kicad_pro")][0][:-10]
    sch = os.path.join(out, name + ".kicad_sch")
    rpt = os.path.join(out, "erc.rpt")
    r = subprocess.run([KICAD_CLI, "sch", "erc", "--format", "report", "-o", rpt, sch],
                       capture_output=True, text=True)
    subprocess.run([KICAD_CLI, "sch", "export", "pdf", "-o", os.path.join(out, name + "-schematic.pdf"), sch],
                   capture_output=True, text=True)
    txt = open(rpt, encoding="utf-8", errors="replace").read() if os.path.exists(rpt) else ""
    m = re.search(r"ERC messages:\s*\d+\s+Errors\s+(\d+)\s+Warnings\s+(\d+)", txt)
    if not m:
        # an unreadable report is a failure, not a pass
        return (1, 0) if r.returncode or not txt else (txt.count("; error"), txt.count("; warning"))
    return int(m.group(1)), int(m.group(2))


def write_bb_library(D):
    """Merge every generic (bb:) symbol used by the design into hardware/lib/bb.kicad_sym.
    X-36: the library is shared by the main and cartridge projects, so symbols already in the file are kept
    (union) and the file is replaced atomically so parallel builds never see a half-written library."""
    import tempfile
    import sexp
    from sexp import Sym
    path = os.path.join(ROOT, "lib", "bb.kicad_sym")
    nodes = {}
    if os.path.exists(path):
        try:
            old = sexp.parse(open(path, encoding="utf-8").read())
            for n in old[1:]:
                if isinstance(n, list) and n and str(n[0]) == "symbol":
                    nodes["bb:" + str(n[1])] = n
        except Exception as e:  # noqa: BLE001 - a corrupt library is rebuilt from this design
            print(f"warning: could not parse existing bb.kicad_sym ({e}); rewriting")
    for sh in D.sheets:
        for p in sh.parts:
            lid = p.sym["lib_id"]
            if lid.startswith("bb:"):
                node = list(p.sym["node"])
                node[1] = lid.split(":", 1)[1]
                nodes[lid] = node
    doc = [Sym("kicad_symbol_lib"), [Sym("version"), 20231120], [Sym("generator"), "bb_gen"]] + \
        [nodes[k] for k in sorted(nodes)]
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(sexp.dump(doc) + "\n")
    os.replace(tmp, path)


def write_project_files(out, name="battery-bank"):
    lib = os.path.relpath(os.path.join(ROOT, "lib"), out).replace("\\", "/")
    with open(os.path.join(out, "sym-lib-table"), "w") as f:
        f.write('(sym_lib_table\n  (version 7)\n'
                f'  (lib (name "lcsc")(type "KiCad")(uri "${{KIPRJMOD}}/{lib}/lcsc.kicad_sym")(options "")(descr "LCSC/EasyEDA parts"))\n'
                f'  (lib (name "bb")(type "KiCad")(uri "${{KIPRJMOD}}/{lib}/bb.kicad_sym")(options "")(descr "Generic R/C/L/D/FET/TP symbols"))\n)\n')
    with open(os.path.join(out, "fp-lib-table"), "w") as f:
        f.write('(fp_lib_table\n  (version 7)\n'
                f'  (lib (name "lcsc")(type "KiCad")(uri "${{KIPRJMOD}}/{lib}/lcsc.pretty")(options "")(descr "LCSC/EasyEDA footprints"))\n)\n')
    pro = os.path.join(out, f"{name}.kicad_pro")
    src = os.path.join(HERE, "project_template.kicad_pro")
    if os.path.exists(src):
        shutil.copy(src, pro)


if __name__ == "__main__":
    sys.exit(main())
